def pct(x):
    return f"{x*100:.2f}%"


def prep(df, kind):
    d = df.copy()
    for c in ['5y', '10y', 'full', 'fullDD', 'roll_mean', 'roll_worst', 'roll_std']:
        if c in d:
            d[c] = d[c].map(pct)
    if 'trades' in d:
        d['trades'] = d['trades'].astype(int)
    else:
        d['trades'] = '—'
    if 'beat' in d:
        d['beat'] = d['beat'].map(lambda x: f"{x*100:.0f}%" if pd.notna(x) else '—')
    elif 'roll_beat' in d:
        d['beat'] = d['roll_beat'].map(lambda x: f"{x*100:.0f}%" if pd.notna(x) else '—')
    return d


def table(d, cols):
    out = ['| ' + ' | '.join(cols) + ' |', '|' + '|'.join(['---'] * len(cols)) + '|']
    for _, r in d.iterrows():
        out.append('| ' + ' | '.join(str(r[c]) for c in cols) + ' |')
    return '\n'.join(out)


